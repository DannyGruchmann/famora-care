/**
 * Angular bakes configuration into the bundle at build time and cannot read it from the process
 * environment at runtime. This script turns SUPABASE_URL / SUPABASE_ANON_KEY into the TypeScript
 * file the app imports.
 *
 * Values come from the process environment (Docker build args on a deploy) or from .env.local
 * during development. Missing values stay empty strings rather than failing the build, so a fresh
 * clone and CI keep working without credentials — the app degrades into a "not configured" state.
 *
 * Everything written here ends up in the public browser bundle. Only the anon / publishable key
 * may go in: it is meant to be public and Row Level Security is what protects the data. The
 * service_role key bypasses RLS entirely, so assertKeyIsPublishable aborts the build on it.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENVIRONMENTS_DIR = resolve(PROJECT_ROOT, 'src/environments');
const ENVIRONMENT_FILE = resolve(ENVIRONMENTS_DIR, 'environment.ts');
const DOTENV_FILE = resolve(PROJECT_ROOT, '.env.local');

function parseDotEnv(content) {
  const entries = content
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith('#'))
    .map((line) => line.split('='))
    .filter((parts) => parts.length > 1)
    .map(([key, ...rest]) => [key.trim(), rest.join('=').trim()]);

  return Object.fromEntries(entries);
}

function readDotEnvLocal() {
  if (!existsSync(DOTENV_FILE)) return {};
  return parseDotEnv(readFileSync(DOTENV_FILE, 'utf8'));
}

function resolveCredentials() {
  const local = readDotEnvLocal();
  return {
    supabaseUrl: process.env.SUPABASE_URL ?? local.SUPABASE_URL ?? '',
    supabaseAnonKey: process.env.SUPABASE_ANON_KEY ?? local.SUPABASE_ANON_KEY ?? '',
    // The Turnstile site key is meant to be public — it identifies the widget, not a secret.
    // Empty is a valid value: the forms it would sit on then render without a CAPTCHA.
    turnstileSiteKey: process.env.TURNSTILE_SITE_KEY ?? local.TURNSTILE_SITE_KEY ?? '',
  };
}

function decodeJwtPayload(token) {
  const segments = token.split('.');
  if (segments.length !== 3) return null;

  try {
    return JSON.parse(Buffer.from(segments[1], 'base64url').toString('utf8'));
  } catch {
    return null;
  }
}

/**
 * Supabase secret keys are recognisable without a network call: the current format carries an
 * sb_secret_ prefix, the legacy JWT format a "role": "service_role" claim.
 */
function isSecretKey(key) {
  if (key.startsWith('sb_secret_')) return true;
  return decodeJwtPayload(key)?.role === 'service_role';
}

function assertKeyIsPublishable(supabaseAnonKey) {
  if (!isSecretKey(supabaseAnonKey)) return;

  console.error(
    'generate-environment: build aborted. SUPABASE_ANON_KEY holds a Supabase service_role key, ' +
      'which bypasses Row Level Security. This value is compiled into the public browser bundle ' +
      'and would expose the entire database. Pass the anon / publishable key instead.',
  );
  process.exit(1);
}

/** Prettier is configured for single quotes, so the generated file has to match the project style. */
function toSingleQuotedLiteral(value) {
  const escaped = JSON.stringify(value).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'");

  return `'${escaped}'`;
}

function renderEnvironmentFile({ supabaseUrl, supabaseAnonKey, turnstileSiteKey }) {
  return [
    '// Generated by scripts/generate-environment.mjs — edits are overwritten on the next build.',
    "import type { Environment } from './environment.types';",
    '',
    'export const environment: Environment = {',
    `  supabaseUrl: ${toSingleQuotedLiteral(supabaseUrl)},`,
    `  supabaseAnonKey: ${toSingleQuotedLiteral(supabaseAnonKey)},`,
    `  turnstileSiteKey: ${toSingleQuotedLiteral(turnstileSiteKey)},`,
    '};',
    '',
  ].join('\n');
}

function warnAboutMissingCredentials({ supabaseUrl, supabaseAnonKey }) {
  if (supabaseUrl.length > 0 && supabaseAnonKey.length > 0) return;
  console.warn(
    'generate-environment: SUPABASE_URL / SUPABASE_ANON_KEY are empty. ' +
      'Set them in .env.local for local development or as Docker build args for a deploy.',
  );
}

function generateEnvironmentFile() {
  const credentials = resolveCredentials();
  assertKeyIsPublishable(credentials.supabaseAnonKey);

  mkdirSync(ENVIRONMENTS_DIR, { recursive: true });
  writeFileSync(ENVIRONMENT_FILE, renderEnvironmentFile(credentials));
  warnAboutMissingCredentials(credentials);
}

generateEnvironmentFile();
